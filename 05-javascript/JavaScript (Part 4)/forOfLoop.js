// for-of Loop is used to iterate over iterable objects like arrays, strings, maps, sets, etc. It provides a simpler and cleaner syntax compared to traditional for loops.

// Example 1: Iterating over an array
const fruits = ['apple', 'banana', 'cherry','date'];

for (const fruit of fruits) {
    console.log(fruit);
}

// Example 2: Iterating over a string
const greeting = 'Hello';
for (const char of greeting) {
    console.log(char);
}