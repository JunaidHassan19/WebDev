let cars = ["BMW", "Mercedes", "Audi", "Toyota", "Honda"];
console.log(cars);

cars.push("Nissan"); // Adds "Nissan" to the end of the array
console.log(cars);

cars.pop(); // Removes the last element from the array
console.log(cars);

cars.unshift("Kia"); // Adds "Kia" to the beginning of the array
console.log(cars);

cars.shift(); // Removes the first element from the array
console.log(cars);