function greet(name) {
  console.log("Hello, " + name + "!");
}

greet("Juni");

function add(a, b) {
  console.log(a + b);
}

add(5, 3);

function personInfo(name, age) {
  console.log("Name: " + name + ", Age: " + age);
}

personInfo("Alice", 30);


